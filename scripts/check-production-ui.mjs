import assert from 'node:assert/strict';
import { createDemoState, previewMealChange, previewCorrection, confirmPreview, todaySelection, groceryItems, groceryEffect, recordFeedback, readiness } from '../docs/prototypes/production-ui/prototype.js';

const today = createDemoState();
assert.equal(todaySelection(today), null, 'unconfirmed date has no Today dinner');
today.plans[0].confirmed = true;
assert.equal(todaySelection(today).slot.id, 'slot-0');
today.sampleDate = '2026-10-06';
assert.equal(todaySelection(today).slot.id, 'slot-1', 'Today follows the sample date');
today.sampleDate = '2026-10-12';
assert.equal(todaySelection(today), null, 'another date does not fall back to slot zero');
today.sampleDate = '2026-10-05';
today.plans.push({ ...structuredClone(today.plans[0]), id: 'overlap' });
assert.equal(todaySelection(today), null, 'overlapping confirmed slots need explicit choice');
today.todayChoice = { planId: 'overlap', slotId: 'slot-0', date: today.sampleDate };
assert.equal(todaySelection(today).plan.id, 'overlap');
today.plans.pop();
today.plans[0].slots.push({ ...structuredClone(today.plans[0].slots[0]), id: 'extra-slot' });
today.todayChoice = null;
assert.equal(todaySelection(today), null, 'multiple slots in one confirmed plan also require choice');

const unchanged = createDemoState();
assert.equal(previewMealChange(unchanged, 'plan-week', 'slot-0', 'fajitas'), null, 'keeping the source meal must retain its leftover link');
assert.equal(unchanged.plans[0].slots[1].sourceId, 'slot-0');
unchanged.plans[0].slots[1].capacity = 'normal';
const explicitCooking = previewMealChange(unchanged, 'plan-week', 'slot-1', 'fajitas');
assert.equal(explicitCooking.changes[0].sourceId, null, 'an explicit leftover-to-cooking change remains possible');

const twoPlans = createDemoState();
twoPlans.plans.push({ ...structuredClone(twoPlans.plans[0]), id: 'other-plan' });
const firstItems = groceryItems(twoPlans, 'plan-week');
const secondItems = groceryItems(twoPlans, 'other-plan');
twoPlans.plans[0].shopping = { confirmed: true, checkedItems: [firstItems[0].id], unavailable: [], snapshot: structuredClone(firstItems), history: [structuredClone(firstItems)] };
twoPlans.plans[1].shopping = { confirmed: true, checkedItems: [secondItems[1].id], unavailable: [secondItems[0].id], snapshot: structuredClone(secondItems), history: [structuredClone(secondItems)] };
twoPlans.selectedPlanId = 'other-plan';
const otherPreview = previewMealChange(twoPlans, 'plan-week', 'slot-0', 'stir-fry');
assert.equal(confirmPreview(twoPlans, otherPreview).ok, true);
assert.equal(twoPlans.plans[0].shopping.confirmed, false, 'repair invalidates only the target plan shopping');
assert.equal(twoPlans.plans[1].shopping.confirmed, true, 'another plan shopping remains confirmed');
assert.deepEqual(twoPlans.plans[1].shopping.checkedItems, [secondItems[1].id]);
assert.deepEqual(twoPlans.plans[1].shopping.unavailable, [secondItems[0].id]);
assert.deepEqual(twoPlans.plans[1].shopping.history[0], secondItems);
twoPlans.selectedPlanId = 'plan-week';
assert.deepEqual(twoPlans.plans[0].shopping.checkedItems, [], 'target plan removed ingredient loses its check');
assert.deepEqual(twoPlans.plans[0].shopping.snapshot, firstItems);

const shopping = createDemoState();
shopping.plans[0].confirmed = true;
const oldItems = groceryItems(shopping);
shopping.plans[0].shopping.snapshot = structuredClone(oldItems);
shopping.plans[0].shopping.confirmed = true;
shopping.plans[0].shopping.checkedItems = [oldItems.find((item) => item.id.includes('slot-2')).id];
const shoppingPreview = previewMealChange(shopping, 'plan-week', 'slot-0', 'stir-fry');
const effect = groceryEffect(shopping, shoppingPreview);
assert(effect.added.some((item) => item.name === '1 broccoli'));
assert(effect.removed.some((item) => item.name === '3 peppers'));
assert(effect.retained.some((item) => item.id === shopping.plans[0].shopping.checkedItems[0]));
assert.equal(confirmPreview(shopping, shoppingPreview).ok, true);
assert(groceryItems(shopping).some((item) => item.name === '1 broccoli'), 'current list follows repair');
assert(!groceryItems(shopping).some((item) => item.name === '3 peppers'), 'removed ingredients leave current list');
assert.deepEqual(shopping.plans[0].shopping.snapshot, oldItems, 'original shopping stays in history');
assert.equal(shopping.plans[0].shopping.confirmed, false, 'repaired current list needs new confirmation');
assert.deepEqual(shopping.plans[0].shopping.checkedItems, [oldItems.find((item) => item.id.includes('slot-2')).id]);

const feedbackState = createDemoState();
const source = feedbackState.plans[0].slots[0];
recordFeedback(feedbackState, 'plan-week', source.id, ['accepted', 'absent', null], null, null);
assert.deepEqual(source.feedback, ['accepted', 'absent', null]);
assert.equal(source.leftoversProduced, null);
recordFeedback(feedbackState, 'plan-week', source.id, ['accepted', 'rejected', null], 20, false);
assert.equal(source.feedbackHistory.length, 1, 'earlier response is inspectable');
assert.deepEqual(source.feedbackHistory[0].responses, ['accepted', 'absent', null]);
assert.equal(source.leftoversProduced, false);
recordFeedback(feedbackState, 'plan-week', source.id, ['accepted', 'rejected', null], 20, false);
assert.equal(source.leftoversProduced, false, 'reopening retains the negative leftover answer');
assert.equal(readiness(feedbackState).leftovers, false, 'failed leftovers change readiness');
feedbackState.meals.find((meal) => meal.id === 'fajitas').safe = false;
assert.equal(readiness(feedbackState).compatible, false);
feedbackState.meals.find((meal) => meal.id === 'fajitas').safe = true;
feedbackState.plans[0].slots[0].capacity = 'hands-off';
assert.equal(readiness(feedbackState).capacity, false);

const s = createDemoState();
s.plans[0].confirmed = true;
const preview = previewMealChange(s, 'plan-week', 'slot-0', 'stir-fry');
assert.deepEqual(preview.changes.map((c) => c.slotId), ['slot-0', 'slot-1']);
assert.equal(preview.changes[1].after, 'chili');
const original = structuredClone(s.plans);
s.revision++;
assert.equal(confirmPreview(s, preview).ok, false, 'a stale preview must not save');
assert.deepEqual(s.plans, original, 'a stale preview must preserve the plan');
s.revision--;
assert.equal(confirmPreview(s, preview).ok, true);
assert.equal(s.plans[0].slots[1].sourceId, null);
assert.equal(s.repairs.length, 1);

const completed = createDemoState();
completed.plans[0].slots[1].completed = true;
assert.throws(() => previewMealChange(completed, 'plan-week', 'slot-0', 'stir-fry'), /completed leftover/i);

const unsafe = createDemoState();
unsafe.meals.find((meal) => meal.id === 'chili').safe = false;
assert.throws(() => previewMealChange(unsafe, 'plan-week', 'slot-0', 'stir-fry'), /replacement|compatible/i, 'a dependency repair must not choose an unconfirmed replacement');
const corrected = createDemoState();
corrected.plans[0].slots[2].completed = true;
corrected.plans[0].slots[2].feedback = ['accepted', 'absent'];
corrected.plans[0].slots[2].elapsed = 30;
const correction = previewCorrection(corrected, 'plan-week', 'slot-2');
assert.equal(confirmPreview(corrected, correction).ok, true);
assert.equal(corrected.plans[0].slots[2].mealId, 'takeout');
assert.equal(corrected.plans[0].slots[2].completed, true);
assert.equal(corrected.plans[0].slots[0].mealId, 'fajitas', 'a correction must use its explicit dinner context');
assert.deepEqual(corrected.corrections[0].before.feedback, ['accepted', 'absent']);
assert.equal(corrected.corrections[0].before.elapsed, 30);
console.log('Prototype checks pass: Today selection, unchanged source, plan-scoped shopping, repair groceries/history, feedback, readiness, stale previews, and correction context.');
