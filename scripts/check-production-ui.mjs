import assert from 'node:assert/strict';
import { createDemoState, eligible, changeCapacity, previewMealChange, previewCorrection, confirmPreview, todaySelection, groceryItems, groceryEffect, recordFeedback, readiness } from '../docs/prototypes/production-ui/prototype.js';

const today = createDemoState();
assert.equal(todaySelection(today), null, 'unconfirmed date has no Today dinner');
today.plans[0].confirmed = true;
assert.equal(todaySelection(today).slot.id, 'slot-0');
today.sampleDate = '2026-10-06';
assert.equal(todaySelection(today).slot.id, 'slot-1', 'Today follows the sample date');
today.sampleDate = '2026-10-12';
assert.equal(todaySelection(today), null, 'another date does not fall back to slot zero');
today.sampleDate = '2026-10-05';
today.plans.push({ ...structuredClone(today.plans[0]), id: 'overlap' });
assert.equal(todaySelection(today), null, 'overlapping confirmed slots need explicit choice');
today.todayChoice = { planId: 'overlap', slotId: 'slot-0', date: today.sampleDate };
assert.equal(todaySelection(today).plan.id, 'overlap');
today.plans.pop();
today.plans[0].slots.push({ ...structuredClone(today.plans[0].slots[0]), id: 'extra-slot' });
today.todayChoice = null;
assert.equal(todaySelection(today), null, 'multiple slots in one confirmed plan also require choice');

const unchanged = createDemoState();
assert.equal(previewMealChange(unchanged, 'plan-week', 'slot-0', 'fajitas'), null, 'keeping the source meal must retain its leftover link');
assert.equal(unchanged.plans[0].slots[1].sourceId, 'slot-0');
unchanged.plans[0].slots[1].capacity = 'normal';
const explicitCooking = previewMealChange(unchanged, 'plan-week', 'slot-1', 'fajitas');
assert.equal(explicitCooking.changes[0].sourceId, null, 'an explicit leftover-to-cooking change remains possible');

const alternatives = createDemoState();
const [, , wednesday, thursday] = alternatives.plans[0].slots;
const monday = alternatives.plans[0].slots[0];
const handsOffChoices = alternatives.meals.filter((meal) => eligible(alternatives, meal, thursday));
assert(handsOffChoices.length >= 3, 'Thursday offers at least three confirmed hands-off meals');
assert.equal(handsOffChoices[0].id, 'chili', 'the initial repair choice remains chili');
assert(handsOffChoices.some((meal) => meal.id === 'chickpea-spinach-curry'));
assert(handsOffChoices.some((meal) => meal.id === 'chicken-white-bean-stew'));
assert(eligible(alternatives, alternatives.meals.find((meal) => meal.id === 'egg-fried-rice'), monday));
assert(eligible(alternatives, alternatives.meals.find((meal) => meal.id === 'pea-tomato-couscous'), monday));
assert(!eligible(alternatives, alternatives.meals.find((meal) => meal.id === 'roast-vegetable-lasagne'), monday));
assert(eligible(alternatives, alternatives.meals.find((meal) => meal.id === 'roast-vegetable-lasagne'), wednesday));
const creamy = alternatives.meals.find((meal) => meal.id === 'creamy-slow-cooker-chicken');
assert(!eligible(alternatives, creamy, thursday), 'unconfirmed hands-off meal needs review');
assert.throws(() => previewMealChange(alternatives, 'plan-week', 'slot-3', creamy.id), /compatibility/i);
creamy.safe = true;
assert(eligible(alternatives, creamy, thursday), 'explicit compatibility confirmation enables the hands-off meal');
assert.equal(previewMealChange(alternatives, 'plan-week', 'slot-3', creamy.id).changes[0].after, creamy.id);

const capacityState = createDemoState();
const capacityBefore = structuredClone(capacityState.plans);
const capacityGroceries = groceryItems(capacityState);
const priorPreview = previewMealChange(capacityState, 'plan-week', 'slot-0', 'stir-fry');
const capacityRevision = capacityState.revision;
assert.deepEqual(changeCapacity(capacityState, 'plan-week', 'slot-0', 'quick', capacityRevision), { ok: true, changed: false });
assert.equal(capacityState.revision, capacityRevision, 'same availability is a no-op');
assert.deepEqual(changeCapacity(capacityState, 'plan-week', 'slot-0', 'hands-off', capacityRevision), { ok: true, changed: true });
assert.equal(capacityState.revision, capacityRevision + 1);
assert.equal(capacityState.plans[0].slots[0].capacity, 'hands-off');
assert.equal(capacityState.plans[0].slots[0].mealId, 'fajitas', 'current meal stays visible until repaired');
assert.equal(capacityState.plans[0].slots[1].sourceId, 'slot-0', 'leftover dependency stays linked');
assert.deepEqual(groceryItems(capacityState), capacityGroceries, 'availability does not alter shopping');
assert.deepEqual(capacityState.plans[0].shopping, capacityBefore[0].shopping, 'shopping history stays fixed');
assert.equal(readiness(capacityState).capacity, false, 'Monday now needs a fitting dinner');
assert.equal(confirmPreview(capacityState, priorPreview).ok, false, 'old dinner preview becomes stale');
const capacityRepair = previewMealChange(capacityState, 'plan-week', 'slot-0', 'chili');
assert.deepEqual(capacityRepair.changes.map((change) => change.slotId), ['slot-0', 'slot-1']);
assert.equal(confirmPreview(capacityState, capacityRepair).ok, true);
assert.equal(readiness(capacityState).capacity, true);

